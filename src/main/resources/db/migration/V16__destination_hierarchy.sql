-- 1. 칼럼 추가 (display_order는 값을 다 채운 뒤 NOT NULL)
ALTER TABLE destination
    ADD COLUMN parent_id     INT,
    ADD COLUMN is_featured   BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN display_order INT;

ALTER TABLE destination
    ADD CONSTRAINT fk_destination_parent
        FOREIGN KEY (parent_id) REFERENCES destination (destination_id)
            ON DELETE RESTRICT;

-- 2. 이름 UNIQUE 교체 — 전체 유일 → 부모 안에서 유일. 시도 노드(parent_id NULL)끼리도
--    중복을 막기 위해 NULLS NOT DISTINCT(PG 15+) (§7-7)
ALTER TABLE destination DROP CONSTRAINT uk_destination_name;
ALTER TABLE destination
    ADD CONSTRAINT uk_destination_parent_name UNIQUE NULLS NOT DISTINCT (parent_id, destination_name);

